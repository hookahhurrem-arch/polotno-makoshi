function parseReading(raw: string): DayReading | null {
  const cleaned = raw.replace(/```json|```/g, "").trim();
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start < 0 || end <= start) return null;
  try {
    const obj = JSON.parse(cleaned.slice(start, end + 1)) as Record<string, unknown>;
    const dayLine = String(obj.dayLine ?? "").trim();
    const dayLooks = String(obj.dayLooks ?? "").trim();
    const dayDo = String(obj.dayDo ?? "").trim();
    const dayAvoid = String(obj.dayAvoid ?? "").trim();
    if (dayLine.length < 8 || dayLooks.length < 20 || !dayDo || !dayAvoid) return null;
    if (/по здоровью|в отношениях —|в делах —|глухая оборона|не замуровывайся|всё обязательно закончится хорошо/i.test(
      `${dayLine} ${dayLooks} ${dayDo} ${dayAvoid}`,
    ))
      return null;
    return { dayLine, dayLooks, dayDo, dayAvoid };
  } catch {
    return null;
  }
}

