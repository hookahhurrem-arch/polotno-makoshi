export type DayReading = {
  dayLine: string;
  dayLooks: string;
  dayAvoid: string;
  dayDo: string;
};

const inputSchema = z.object({
  number: z.number().int().min(1).max(108),
  title: z.string().max(120),
  keywords: z.string().max(240),
  description: z.string().max(800),
});

function stripHealth(text: string): string {
  return text
    .split(/\n+/)
    .filter((line) => !/здоров|недуг|болезн|бессон|давлен|фоби|травм/i.test(line))
    .map((line) =>
      line
        .replace(/^(В отношениях|В делах и деньгах|В делах|В деньгах|Как человек)\s*[-—:]*\s*/i, "")
        .trim(),
    )
    .filter(Boolean)
    .join(" ");
}

function firstSentence(text: string): string {
  const bits = text.match(/[^.!?]+[.!?]+/g)?.map((s) => s.trim()) ?? [text.trim()];
  return bits[0] || text.trim();
}

function coreOf(description: string, keywords: string, title: string): string {
  const cleaned = stripHealth(description);
  return firstSentence(cleaned) || keywords.trim() || title.trim();
}

